#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

export function readPackageVersion(appRoot) {
  const pkgRaw = fs.readFileSync(path.join(appRoot, 'package.json'), 'utf8');
  const pkg = JSON.parse(pkgRaw);
  return pkg.version;
}

export function syncVersionMetadata(appRoot, options = {}) {
  const log = options.log ?? console.log;
  const version = readPackageVersion(appRoot);
  const buildDate = new Date().toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });

  const buildInfoContent =
    `// Auto-generated by scripts/deploy-bauklank.mjs — do not edit manually\n` +
    `export const APP_VERSION = '${version}';\n` +
    `export const BUILD_DATE = '${buildDate}';\n`;
  fs.writeFileSync(path.join(appRoot, 'src', 'app', 'build-info.ts'), buildInfoContent, 'utf8');
  log(`✅ build-info.ts written: v${version} · ${buildDate}`);

  const ngswConfigPath = path.join(appRoot, 'ngsw-config.json');
  const ngswConfig = JSON.parse(fs.readFileSync(ngswConfigPath, 'utf8'));
  ngswConfig.appData = { version };
  fs.writeFileSync(ngswConfigPath, JSON.stringify(ngswConfig, null, 2) + '\n', 'utf8');
  log(`✅ ngsw-config.json appData.version: ${version}`);

  return { version, buildDate };
}
